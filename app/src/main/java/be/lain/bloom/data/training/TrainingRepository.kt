data class DemoVideo(val id: String, val title: String, val channel: String, val custom: Boolean)

data class ProgramStatus(
    val program: be.lain.bloom.domain.training.TrainingProgram,
    val phase: Phase,
    val phaseStart: LocalDate,
    val week: Int,
    val workoutsInPhase: Int,
    val next: Session,
    /** Enough weeks and workouts done to move on. */
    val readyToAdvance: Boolean,
)

@OptIn(ExperimentalCoroutinesApi::class)
@Singleton
class TrainingRepository @Inject constructor(
    @ApplicationContext private val context: Context,
    private val db: BloomDatabase,
    private val settings: SettingsRepository,
    private val clock: Clock,
) {
    private val dao get() = db.trainingDao()
    private val json = Json { ignoreUnknownKeys = true }

    /** Default demo videos from assets/videos.json (generated by scripts/verify_videos.py). */
    private val defaultVideos: Map<String, DemoVideo> by lazy {
        runCatching {
            val text = context.assets.open("videos.json").bufferedReader().use { it.readText() }
            json.parseToJsonElement(text).jsonObject.mapValues { (_, v) ->
                val o = v.jsonObject
                DemoVideo(o["id"]!!.jsonPrimitive.content, o["title"]?.jsonPrimitive?.contentOrNull.orEmpty(),
                    o["channel"]?.jsonPrimitive?.contentOrNull.orEmpty(), false)
            }
        }.getOrDefault(emptyMap())
    }

    val videos: Flow<Map<String, DemoVideo>> = dao.observeVideos().map { overrides ->
        defaultVideos + overrides.associate { it.exerciseId to DemoVideo(it.youtubeId, it.title, "", true) }
    }

    suspend fun setVideo(exerciseId: String, youtubeId: String, title: String) = dao.setVideo(VideoOverrideEntity(exerciseId, youtubeId, title))
    suspend fun resetVideo(exerciseId: String) = dao.clearVideo(exerciseId)

    val workouts = dao.observeWorkouts()
    val choices: Flow<Map<String, String>> = dao.observeChoices().map { list -> list.associate { it.slotKey to it.exerciseId } }

    suspend fun setChoice(slotKey: String, exerciseId: String, default: String) {
        if (exerciseId == default) dao.clearChoice(slotKey) else dao.setChoice(SlotChoiceEntity(slotKey, exerciseId))
    }

    val status: Flow<ProgramStatus> = settings.settings.flatMapLatest { s ->
        val program = be.lain.bloom.domain.training.Programs.byId(s.programId)
        val start = s.phaseStartEpochDay?.let(LocalDate::ofEpochDay) ?: LocalDate.now(clock)
        val phase = program.phase(s.programPhase)
        dao.observeCountInPhase(program.id, phase.index, start).map { count ->
            val week = (ChronoUnit.DAYS.between(start, LocalDate.now(clock)) / 7 + 1).toInt().coerceAtLeast(1)
            ProgramStatus(
                program = program, phase = phase, phaseStart = start, week = week, workoutsInPhase = count,
                next = phase.sessions[count % phase.sessions.size],
                readyToAdvance = program.readyToAdvance(phase, week, count),
            )
        }
    }

    suspend fun ensureStarted() {
        if (settings.settings.first().phaseStartEpochDay == null) settings.setPhase(0, LocalDate.now(clock).toEpochDay())
    }

    suspend fun setPhase(index: Int) {
        val program = be.lain.bloom.domain.training.Programs.byId(settings.settings.first().programId)
        settings.setPhase(index.coerceIn(0, program.phases.lastIndex), LocalDate.now(clock).toEpochDay())
    }

    /** Switches to another program, resuming its saved phase if it was used before. */
    suspend fun setProgram(id: String) = settings.setProgram(be.lain.bloom.domain.training.Programs.byId(id).id, LocalDate.now(clock).toEpochDay())

    suspend fun lastForSlot(slot: String) = dao.lastForSlot(slot)

    suspend fun saveWorkout(w: WorkoutSessionEntity, results: Collection<SetResult>): Long = db.withTransaction {
        val id = dao.insertWorkout(w)
        dao.insertSets(results.map {
            SetLogEntity(workoutId = id, exerciseId = it.exerciseId, slotKey = it.slotKey, setIndex = it.setIndex, side = it.side,
                reps = it.reps, seconds = it.seconds, effort = it.effort, skipped = it.skipped)
        })
        id
    }

    suspend fun updateWorkout(w: WorkoutSessionEntity) = dao.updateWorkout(w)
    suspend fun deleteWorkout(id: Long) = db.withTransaction { dao.deleteSets(id); dao.deleteWorkout(id) }
    suspend fun workout(id: Long) = dao.workout(id)
    suspend fun sets(id: Long) = dao.sets(id)
    suspend fun workoutsBetween(from: LocalDate, to: LocalDate) = dao.workouts(from, to)

    /** Variation actually used for each slot of a session. */
    fun choicesFor(map: Map<String, String>): (String, String) -> String = { slot, default -> map[slot] ?: default }
}

/** Gives the AI coach a view of strength training. */
class StrengthContext @Inject constructor(private val repo: TrainingRepository) : TrainingContext {
    override suspend fun summary(from: LocalDate, to: LocalDate): JsonObject {
        val st = repo.status.first()
        val list = repo.workoutsBetween(from, to)
        return buildJsonObject {
            put("strength_program", buildJsonObject {
                put("name", st.program.name)
                put("phase", "${st.phase.index + 1}/${st.program.phases.size} ${st.phase.name} (week ${st.week} of ${st.phase.weeks})")
                put("phase_summary", st.phase.summary)
                put("other_programs", be.lain.bloom.domain.training.Programs.all.filter { it.id != st.program.id }
                    .joinToString("; ") { "${it.id}: ${it.name} (${it.tagline}, ${it.sessionsPerWeek}×/week, ${it.level})" })
                put("workouts_in_phase", st.workoutsInPhase)
                put("next_session", st.next.name)
            })
            put("strength_workouts", buildJsonArray {
                list.forEach { w ->
                    add(buildJsonObject {
                        put("date", w.date.toString()); put("name", w.name); put("minutes", w.activeSeconds / 60)
                        put("sets", "${w.setsDone}/${w.setsPlanned}"); w.rpe?.let { put("rpe", it) }; put("kcal", w.kcal)
                        if (w.notes.isNotBlank()) put("notes", w.notes)
                    })
                }
            })
        }
    }
}

@Module
@InstallIn(SingletonComponent::class)
abstract class TrainingModule {
    @Binds @IntoSet abstract fun strength(c: StrengthContext): TrainingContext
}
