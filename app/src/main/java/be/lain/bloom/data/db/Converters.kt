package be.lain.bloom.data.db

import androidx.room.TypeConverter
import be.lain.bloom.domain.Serving
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.time.DayOfWeek
import java.time.Instant
import java.time.LocalDate

class Converters {
    @TypeConverter fun dateToLong(d: LocalDate?): Long? = d?.toEpochDay()
    @TypeConverter fun longToDate(v: Long?): LocalDate? = v?.let(LocalDate::ofEpochDay)

    @TypeConverter fun instantToLong(i: Instant?): Long? = i?.toEpochMilli()
    @TypeConverter fun longToInstant(v: Long?): Instant? = v?.let(Instant::ofEpochMilli)

    @TypeConverter fun daysToString(days: Set<DayOfWeek>?): String? =
        days?.sorted()?.joinToString(",") { it.value.toString() }

    @TypeConverter fun stringToDays(s: String?): Set<DayOfWeek>? =
        s?.split(',')?.filter { it.isNotBlank() }?.map { DayOfWeek.of(it.trim().toInt()) }?.toSet()

    // Built by hand: Room's KSP step can't see serializers generated by the serialization plugin.
    @TypeConverter fun servingsToString(v: List<Serving>?): String? = v?.let { list ->
        JsonArray(list.map { JsonObject(mapOf("label" to JsonPrimitive(it.label), "grams" to JsonPrimitive(it.grams))) }).toString()
    }

    @TypeConverter fun stringToServings(s: String?): List<Serving>? = s?.let {
        runCatching {
            Json.parseToJsonElement(it).jsonArray.map { e ->
                val o = e.jsonObject
                Serving(o["label"]!!.jsonPrimitive.content, o["grams"]!!.jsonPrimitive.doubleOrNull ?: 0.0)
            }
        }.getOrDefault(emptyList())
    }
}
